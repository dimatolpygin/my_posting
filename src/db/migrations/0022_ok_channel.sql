-- Этап 1: канал публикации ВК → Одноклассники.
--
-- Схема почти не меняется — конвейеру всё равно, в какую соцсеть уходит пост. Меняются
-- три вещи, каждая из которых иначе тихо ввела бы в заблуждение того, кто читает базу.
--
-- 1. Номер канала переезжает в настройку. В коде он теперь дефолт (`CHANEL_OK = 5`),
--    а рабочее значение читается отсюда: переключить соцсеть можно, не пересобирая образ.
--    Значение 5 снято с живого `GET /accounts` 26.08.2026 — в справочнике postmypost
--    Одноклассников нет вовсе, список там неполон.
--
-- 2. `publications.vk_url` → `publications.post_url`. Колонка хранит адрес опубликованной
--    записи, и в проекте про Одноклассники имя `vk_url` — прямая ложь для того, кто
--    полезет в базу через полгода.
--
-- 3. Комментарии к колонкам. Исходные тексты в `0002` и `0010` утверждают, что
--    `groups.external_id` — «id сообщества со знаком минус». Это правда для ВК и неправда
--    для ОК: там id положительный (`70000055464414`). Применённые миграции не правятся —
--    ловушка по контрольной сумме сработает и будет права, — поэтому истина дописывается
--    комментарием к колонке: он живёт в самой базе и виден в любом клиенте.

-- ── 1. Канал ────────────────────────────────────────────────────────────────
INSERT INTO settings (key, value, title)
VALUES ('pmp_chanel_id', '5', 'Канал postmypost: 5 — Одноклассники, 2 — ВК, 6 — Telegram')
ON CONFLICT (key) DO NOTHING;

-- ── 2. Переименование колонки ───────────────────────────────────────────────
-- Идемпотентно: миграция применяется один раз, но на базе, поднятой с нуля уже после
-- этой правки, колонки `vk_url` не будет вовсе — а падать на этом незачем.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_name = 'publications' AND column_name = 'vk_url'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_name = 'publications' AND column_name = 'post_url'
  ) THEN
    ALTER TABLE publications RENAME COLUMN vk_url TO post_url;
  END IF;
END $$;

ALTER TABLE publications ADD COLUMN IF NOT EXISTS post_url text;

-- ── 3. Комментарии ──────────────────────────────────────────────────────────
COMMENT ON COLUMN groups.external_id IS
  'id группы в Одноклассниках, положительный: ok.ru/group/70000055464414. '
  'Знак минус — специфика ВК, здесь его нет.';

COMMENT ON COLUMN publications.post_url IS
  'Адрес опубликованной темы: ok.ru/group/{id}/topic/{id}. Появляется не сразу — '
  'у черновика и у отложенного поста темы ещё не существует.';

COMMENT ON COLUMN groups.pmp_account_id IS
  'id аккаунта в postmypost. Группа подключается там, числовые id руками не вводятся.';
