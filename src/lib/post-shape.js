/**
 * Какого вида тема получится из этого запроса.
 *
 * Видов два, и они требуют разной структуры текста:
 *
 * - `разбор` — запрос спрашивает, как что-то устроено, сколько стоит, можно ли,
 *   чем заменить. Человеку нужен ответ; выдуманный диалог с клиентом в такой теме
 *   выглядит натяжкой и обесценивает весь текст.
 * - `продукт` — запрос описывает ситуацию в бизнесе, которую закрывает наша работа.
 *   Здесь пример диалога и есть самое ценное: он показывает продукт лучше описания.
 *
 * Почему вид определяется кодом, а не моделью. Во-первых, от него зависит проверка
 * готового текста: требовать диалог в разборе нельзя, а в продуктовой теме нужно, и
 * проверка обязана знать, что именно она проверяет. Во-вторых, дешёвая модель
 * классифицирует нестабильно: один и тот же запрос на двух прогонах уходит в разные
 * стороны, и объяснить разницу в тексте потом нечем.
 *
 * Разбор — значение по умолчанию: из ста наших запросов подавляющее большинство
 * это вопросы, а натянутый рассказ про агента там, где спрашивали про другое,
 * читатель распознаёт с первого абзаца.
 */

/**
 * Вопросительные зачины и обороты. Список закрытый и намеренно короткий: он проверяем
 * глазами по списку тем, в отличие от «умной» классификации.
 */
const QUESTION_MARKERS = [
  'как ', 'какой', 'какая', 'какие', 'какую', 'каким', 'сколько',
  'что такое', 'что делать', 'что можно', 'что вы', 'что законно', 'что за ',
  'чем заменить', 'чем отличается', 'чем это', 'где ', 'куда ', 'откуда ',
  'зачем', 'почему', 'за что', 'из чего', 'или ', 'простыми словами',
  'расходы', 'документы на', 'что реально',
];

/**
 * Частица «ли» — самый надёжный признак вопроса, и ловить её списком («можно ли»,
 * «нужно ли», «может ли», «умеет ли», «стоит ли»…) бессмысленно: список всегда
 * окажется короче языка. Проверяем отдельным словом.
 */
const PARTICLE_LI = /(^|\s)ли(\s|$)/;

/** Слова, после которых тема почти всегда про нашу работу, даже если начинается с вопроса. */
const PRODUCT_MARKERS = [
  'бот для записи', 'автоответчик', 'не успевает', 'теряются', 'уволил',
  'вместо менеджера', 'приходит сам', 'отвечает клиент',
];

/**
 * @param {string} phrase поисковая фраза (она же заголовок темы)
 * @returns {'разбор'|'продукт'}
 */
export function postShape(phrase) {
  const value = String(phrase ?? '').toLowerCase().replace(/ё/g, 'е').trim();
  if (!value) return 'разбор';

  if (PRODUCT_MARKERS.some((marker) => value.includes(marker))) return 'продукт';
  if (value.includes('?')) return 'разбор';
  if (PARTICLE_LI.test(value)) return 'разбор';
  if (QUESTION_MARKERS.some((marker) => value.startsWith(marker) || value.includes(' ' + marker))) {
    return 'разбор';
  }
  return 'продукт';
}

/** Нужен ли в теме этого вида блок с диалогом. */
export function needsDialogue(shape) {
  return shape === 'продукт';
}
