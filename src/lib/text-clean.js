/**
 * Постобработка сгенерированного текста.
 *
 * Зачем кодом, а не промтом: просить модель «не используй markdown и длинное тире»
 * работает через раз, а чистка регулярками работает всегда. Промт отвечает за стиль,
 * код — за чистоту разметки.
 *
 * Что НЕЛЬЗЯ трогать (осознанный стиль, а не мусор):
 *   - сами булиты в начале строки: так устроен формат поста в промте;
 *   - эмодзи-иконки в подзаголовках: для ОК и аудитории 30+ они работают;
 *   - разделители «--------» вокруг рекламного блока.
 *
 * Чистка идёт по тексту МОДЕЛИ, до сборки готовой темы: заголовок и хвост
 * приклеивает код, и чистить в них нечего.
 *
 * Что делается с тире: внутри предложения оно убирается, а там, где остаётся
 * (булиты, рекламный блок), длинное «—» заменяется коротким «-». Длинных тире
 * в готовом тексте не остаётся вообще — требование заказчика.
 */

/** Строка-булит: тире (или дефис) с пробелом в начале строки. Сам булит сохраняем. */
const BULLET_LINE = /^(\s*)[—–-]\s+/;

/** Длинное и среднее тире. В готовом тексте их быть не должно — только дефис. */
const LONG_DASH = /[—–]/g;

/**
 * Вода: обороты, которые занимают место и не сообщают ничего. Все до одного
 * пойманы в живых текстах системы. «Стоимость зависит от сложности задачи» —
 * это ровно та строка, ради которой человек НЕ открывал тему: он и так знал,
 * что зависит, он пришёл узнать, от чего именно и сколько примерно.
 *
 * Список работает дважды: сначала `dropWaterSentences` вырезает предложения
 * с этими оборотами, потом `validateModelText` ловит то, что вырезать нельзя.
 */
const WATER = [
  'зависит от сложности',
  'зависит от объ',
  'будет зависеть от',
  'цены могут варьироваться',
  'стоимость может варьироваться',
  'может варьироваться',
  'варьируется в зависимости',
  'у каждого свои особенности',
  'каждый случай уникален',
  'подбирается под задачу',
  'в зависимости от потребност',
  'рассчитывается индивидуально',
  'определяется индивидуально',
  'в каждом случае по-разному',
  'сроки обсуждаются',
  'повысит эффективность',
  'оптимизировать процессы',
  'на новый уровень',
  'существует множество',
  'займёт время, завис',
  'зависящее от сложности',
  // «набор решений, зависящих от ваших задач и бюджета» — финал темы с прода
  'зависящ',
];

/**
 * Пустые зачины. От воды выше отличаются тем, что за ними обычно идёт смысл:
 * «Важно понимать, что провайдеры блокируют сами протоколы» — предложение
 * полезное, лишние в нём только первые два слова. Поэтому такой зачин срезается,
 * а предложение остаётся, с большой буквы.
 */
const WATER_PREFIX = /^(важно понимать|стоит отметить|следует учитывать|не стоит забывать|надо понимать|хочу отметить)[,:]?\s*(что\s+)?/i;

/**
 * Выдуманный адрес с номером дома. Модель вставляет его в пример диалога («Приезжайте
 * на улицу Ленина, дом 10»), потому что так разговор выглядит правдоподобнее. Адрес
 * при этом взят из воздуха, а читается в открытом посте как чужие персональные данные —
 * и именно так его прочтёт тот, кто на такие вещи смотрит внимательно.
 *
 * Заменяем, а не вырезаем: «Приезжайте на» без продолжения выглядит как обрыв.
 * Правило есть и в промте, и в проверке, но модель возвращала тот же адрес три
 * попытки подряд — дешевле подменить строкой, чем сжечь на этом тему.
 */
const FAKE_ADDRESS =
  /(?:(?:^|\s)(?:по\s+адресу|адрес|на|в|по)\s+)?(?:ул\.|улиц\w*|проспект\w*|пр-?т|переул\w*|шоссе|бульвар\w*)[^.,;\n]{2,40}[,\s]+(?:д\.|дом)?\s*\d+(?:\s*,?\s*(?:кв\.|квартира)\s*\d+)?/gi;

/** Ряд дефисов — разделитель рекламного блока из промта, не markdown-hr. */
const AD_SEPARATOR = /^\s*-{4,}\s*$/;

/**
 * Строка-подзаголовок «Итог». Промт просит её не писать, модель пишет всё равно —
 * и правильно делает по-своему: в инструкции блок так и называется. Проще снять
 * строку кодом, чем сжигать на ней попытку: абзац под ней и так читается как итог,
 * а служебное слово выдаёт шаблон.
 */
const SUMMARY_HEADING = /^\s*[^\p{L}\d]{0,4}\s*(итог|итоги|вывод|выводы|заключение)\s*[:.]?\s*$/iu;

function stripMarkdownInline(line) {
  return line
    // ссылки [текст](url) → «текст (url)»: ссылку из рекламного блока терять нельзя
    // Сравнение без хвостового слэша: модель часто пишет [https://site.ru](https://site.ru/),
    // и строгое равенство оставляло ссылку в тексте дважды.
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, (_, text, url) => {
      const bare = (value) => value.trim().replace(/\/+$/, '');
      return bare(text) === bare(url) ? url.trim() : `${text} ${url}`;
    })
    // **жирный**, __жирный__, *курсив*, _курсив_
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/(^|[\s(«"])\*([^*\n]+)\*(?=[\s).,!?»"]|$)/g, '$1$2')
    .replace(/(^|[\s(«"])_([^_\n]+)_(?=[\s).,!?»"]|$)/g, '$1$2')
    // `код` и ~~зачёркнутый~~
    .replace(/`([^`]+)`/g, '$1')
    .replace(/~~([^~]+)~~/g, '$1')
    // «https://site.ru (https://site.ru/)» → одна ссылка. Так выглядит уже разобранная
    // markdown-ссылка, у которой текст и адрес различались только слэшем.
    .replace(/(https?:\/\/[^\s()]+?)\/?\s+\((https?:\/\/[^\s()]+?)\/?\)/g, (match, first, second) =>
      first === second ? first : match);
}

/**
 * Пункт-ярлык: «- Блокировка аккаунта: использование сервисов из неподдерживаемой
 * территории приводит к бану». Так пишет конспект, а не человек, и модель скатывается
 * в этот вид списка в каждом втором тексте, сколько ей ни запрещай.
 *
 * Ярлык срезается только тогда, когда без него остаётся законченное предложение:
 * с большой буквы и не короче тридцати знаков. Если остаток короткий или начинается
 * со строчной, ярлык нёс подлежащее — трогать нельзя, пусть модель перепишет сама.
 */
const BULLET_LABEL = /^(\s*[-]\s+)([А-ЯЁA-Z][^:\n]{1,45}):\s+(?=[А-ЯЁA-Z])/;

function dropBulletLabel(line) {
  const match = line.match(BULLET_LABEL);
  if (!match) return line;
  const rest = line.slice(match[0].length);
  if (rest.trim().length < 30) return line;
  return match[1] + rest;
}

/**
 * Удалить из строки предложения-воду.
 *
 * Условие на цифры принципиально. «Стоимость зависит от сложности задачи» не
 * сообщает ничего и удаляется без потерь — это и есть определение воды. А вот
 * «Лицензия стоит 15000 рублей в год, внедрение зависит от сложности» несёт
 * цифру, ради которой тему и открыли: такое предложение остаётся, и на нём
 * сработает проверка — пусть модель перепишет сама.
 *
 * Пункт списка, от которого после чистки не осталось ничего, кроме дефиса,
 * удаляется целиком: пустой булит выглядит как оборванный текст.
 */
function dropWaterSentences(line) {
  const lower = line.toLowerCase();
  const hasWater = WATER.some((phrase) => lower.includes(phrase));
  const hasPrefix = WATER_PREFIX.test(line.replace(BULLET_LINE, '').trim());
  if (!hasWater && !hasPrefix) return line;

  const bullet = line.match(BULLET_LINE)?.[0] ?? '';
  const body = line.slice(bullet.length);

  const kept = body
    .split(/(?<=[.!?])\s+/)
    .map((sentence) => {
      const trimmed = sentence.trim();
      if (!WATER_PREFIX.test(trimmed)) return sentence;
      const rest = trimmed.replace(WATER_PREFIX, '');
      if (rest.length === 0) return '';
      return rest.charAt(0).toUpperCase() + rest.slice(1);
    })
    .filter((sentence) => {
      const value = sentence.toLowerCase();
      if (value.trim().length === 0) return false;
      if (!WATER.some((phrase) => value.includes(phrase))) return true;
      return /\d/.test(sentence);
    })
    .join(' ')
    .trim();

  if (kept.length === 0) return '';
  return bullet + kept;
}

/**
 * Тире внутри предложения заменяется на запятую или убирается.
 * «Проект — это развод» → «Проект это развод». Тире в начале строки (булит) сохраняется,
 * поэтому обработка идёт построчно и первый символ строки не участвует.
 */
function stripInlineDash(line) {
  const bullet = line.match(BULLET_LINE);
  // Булит сохраняем как маркер, но приводим к короткому дефису.
  const head = bullet ? `${bullet[1]}- ` : '';
  const rest = bullet ? line.slice(bullet[0].length) : line;
  const cleaned = rest
    // «слово — слово» → «слово слово»; двойной пробел подчищается ниже
    .replace(/\s+[—–]\s+/g, ' ')
    // «слово—слово» без пробелов
    .replace(/(\S)[—–](\S)/g, '$1 $2');
  return head + cleaned;
}

export function cleanPostText(raw) {
  if (!raw) return '';

  // Рекламный блок между строками-разделителями — дословный текст клиента.
  // Внутри него не чистим ничего, кроме markdown: там есть «— он принес нам…»,
  // и удаление этого тире ломает фразу заказчика.
  let insideAd = false;

  const lines = String(raw)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => {
      if (AD_SEPARATOR.test(line)) {
        insideAd = !insideAd;
        return line.trim();
      }
      // В рекламном блоке текст клиента дословный: тире там не удаляем (иначе ломается
      // фраза «— он принес нам»), но длинное меняем на короткое.
      if (insideAd) return stripMarkdownInline(line).replace(LONG_DASH, '-').trimEnd();

      let out = line
        // заголовки markdown: решётки убираем, текст оставляем
        .replace(/^\s{0,3}#{1,6}\s+/, '')
        // цитаты
        .replace(/^\s{0,3}>\s?/, '')
        // нумерованные и звёздочные списки приводим к булиту клиента
        .replace(/^\s*\d+[.)]\s+/, '- ')
        .replace(/^\s*[*+]\s+/, '- ');

      out = stripMarkdownInline(out);
      out = stripInlineDash(out);

      return out.replace(/[ \t]{2,}/g, ' ').trimEnd();
    });

  return lines
    // Предлог перед адресом входит в совпадение, иначе выходит «на по адресу».
    .map((line) => line.replace(FAKE_ADDRESS, (m) => (/^\s/.test(m) ? ' по адресу' : 'по адресу')))
    .map(dropBulletLabel)
    .map(dropWaterSentences)
    .filter((line) => !SUMMARY_HEADING.test(line))
    .join('\n')
    // больше двух пустых строк подряд не нужно
    .replace(/\n{3,}/g, '\n\n')
    // Контрольный проход: длинных тире в тексте не остаётся ни в каком виде.
    .replace(LONG_DASH, '-')
    .trim();
}

/**
 * Обрезка лишних пунктов в списках. Последняя мера против переросшего поста, когда
 * модель уже трижды отказалась уложиться в лимит.
 *
 * Почему именно пункты: промт клиента просит по три пункта в двух блоках, а модель
 * регулярно выдаёт по пять-шесть, и именно они дают перебор. Удаление лишних пунктов
 * с конца блока не ломает ни структуру, ни рекламный блок, ни «Итог» — в отличие от
 * обрезки текста по символам, которая оставляет пост оборванным на полуслове.
 *
 * @param {string} text
 * @param {number} keepPerBlock сколько пунктов оставить в каждом блоке
 */
export function trimBulletLists(text, keepPerBlock = 3) {
  const lines = String(text ?? '').split('\n');
  const out = [];
  let insideAd = false;
  let bulletsInBlock = 0;

  for (const line of lines) {
    if (AD_SEPARATOR.test(line)) {
      insideAd = !insideAd;
      bulletsInBlock = 0;
      out.push(line);
      continue;
    }
    // В рекламном блоке не трогаем ничего: это дословный текст клиента.
    if (!insideAd && /^\s*[—–-]\s+\S/.test(line)) {
      bulletsInBlock += 1;
      if (bulletsInBlock > keepPerBlock) continue;
    } else if (line.trim() === '') {
      bulletsInBlock = 0;
    }
    out.push(line);
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * Проверка готового текста темы. Возвращает список нарушений; пустой список = годен.
 * Нарушения уходят модели следующей попыткой — это работает заметно лучше, чем
 * просто повторить тот же запрос.
 *
 * На вход идёт ГОТОВЫЙ текст темы: первая строка-заголовок, тело и подставленный
 * хвост. Не текст модели — его проверяет `validateModelText`.
 *
 * @param {string} text
 * @param {object} rules
 * @param {number} rules.minChars
 * @param {number} rules.maxChars
 * @param {string} [rules.phrase] фраза ключа — она же обязана быть первой строкой
 */
export function validatePost(text, { minChars, maxChars, phrase, shape = 'продукт' }) {
  const problems = [];
  const value = String(text ?? '');

  // Ноль в любом из пределов = ограничения нет.
  if (minChars > 0 && value.length < minChars) {
    problems.push(`коротко: ${value.length} символов, нужно от ${minChars}`);
  }
  if (maxChars > 0 && value.length > maxChars) {
    problems.push(`длинно: ${value.length} символов, нужно до ${maxChars}`);
  }

  // Заголовок. Одноклассники собирают <title> страницы из ПЕРВОЙ СТРОКИ текста —
  // отдельного поля заголовка у темы нет. Значит первая строка обязана быть точной
  // фразой запроса: по ней тема ранжируется, и ничем другим её не заменить.
  if (phrase) {
    const first = value.split('\n')[0].trim();
    if (first !== phrase.trim()) {
      problems.push(`первая строка не равна фразе ключа: «${first.slice(0, 80)}»`);
    }
    // Заголовок, повторённый внутри текста, забирает место в сниппете и читается
    // как заедающая пластинка.
    const body = value.slice(value.indexOf('\n') + 1);
    if (body.includes(phrase.trim())) problems.push('фраза ключа повторена внутри текста');
  }

  // Пример диалога — самая ценная часть ПРОДУКТОВОЙ темы: он показывает работу лучше
  // любого описания, а модель выбрасывает его первым, когда ужимает текст. Поэтому
  // здесь он проверяется кодом.
  const lines = value.split('\n');
  const clientLines = lines.filter((line) => /^\s*клиент\s*:/i.test(line)).length;
  const agentLines = lines.filter((line) => /^\s*агент\s*:/i.test(line)).length;
  //
  // В разборе вопроса всё наоборот: такой диалог выдуман целиком. Тема «как оплатить
  // зарубежный сервис» со сценкой, где агент бодро подбирает криптобиржу, читается
  // как выдумка и обесценивает остальной текст. Вид темы приходит из post-shape.js:
  // его считает код по самой фразе запроса, и обе стороны — промт и проверка —
  // обязаны понимать его одинаково.
  if (shape === 'продукт') {
    if (clientLines < 3 || agentLines < 3) {
      problems.push(
        `нет примера диалога: реплик клиента ${clientLines}, агента ${agentLines}, ` +
          'нужно минимум по 3 в виде «Клиент: …» и «Агент: …»',
      );
    }
  } else if (clientLines > 0 || agentLines > 0) {
    problems.push(
      'убери блок с диалогом: это разбор вопроса, а не рассказ о работе агента, ' +
        'и придуманная переписка тут выглядит натяжкой',
    );
  }

  // Булиты: без них тема читается стеной текста, а её будут листать с телефона.
  const bulletLines = lines.filter((line) => /^\s*[—–-]\s+\S/.test(line)).length;
  if (bulletLines < 4) {
    problems.push(`мало пунктов-булитов: ${bulletLines}, нужно минимум 4 (по 2-3 в двух блоках)`);
  }

  if (/\*\*|^#{1,6}\s|\[[^\]]+\]\(/m.test(value)) {
    problems.push('осталась markdown-разметка');
  }
  if (/[—–]/.test(value)) {
    problems.push('остались длинные тире');
  }

  return problems;
}

