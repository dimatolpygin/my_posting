/**
 * Блоки со ссылкой: верхний, нижний и подстановка адресов.
 *
 * Почему их пишет код, а не модель:
 *
 * 1. **Ссылку модель выдумывает.** Просить её вставить конкретный адрес — значит
 *    получать то правильный, то похожий, то несуществующий. Отловить это валидацией
 *    можно, но каждая отбраковка стоит лишней генерации.
 * 2. **Блок нужен не в каждом посте.** Одинаковый коммерческий хвост в ста процентах
 *    тем быстрее ловит урезание охвата в ОК и подозрение на спам у Яндекса. Решение
 *    «ставить или нет» — арифметика по счётчику, модели её не поручить.
 * 3. **Настоящий адрес известен только после сохранения поста.** Ссылка персональная
 *    (`/k/{post_id}`), а id появляется лишь после вставки в БД. Поэтому в тексте живёт
 *    плейсхолдер, а подстановка идёт отдельным шагом — опубликованную тему задним
 *    числом не отредактировать.
 *
 * Блоков два, и стоят они по краям текста: короткий после первого абзаца и полный
 * в конце. Причина простая: в ленте ОК тему листают, до конца доходит меньшинство,
 * а первый экран видят все. Верхний блок отбивается от текста иконкой и пустыми
 * строками, чтобы читался как отдельный блок, а не как продолжение абзаца.
 *
 * Плейсхолдеры: {ССЫЛКА} — профиль на Kwork, {ССЫЛКА_ВИЗА} — виртуальная карта,
 * {ССЫЛКА_СЕРВЕР} — сервер. В промте их нет вовсе: модель к блокам не притрагивается.
 */

/** Разделитель блока. Ряд дефисов, а не длинное тире: постобработка их не трогает. */
const SEP = '--------';

/**
 * Нижний блок. Две вещи в нём делают работу: цифры отзывов снимают страх работать
 * с фрилансером, «демо до оплаты» снимает риск. Всё остальное — лишние строки.
 */
const KWORK_BLOCK = [
  SEP,
  '🔧 Делаю такие решения на заказ. На Kwork 100+ выполненных проектов и 76 отзывов,',
  'из них 75 положительных - видно, что и кому я делал:',
  '{ССЫЛКА}',
  '',
  'Покажу демо на вашем прайсе до оплаты.',
  SEP,
].join('\n');

/** Верхний блок: одна строка, чтобы не отодвигать текст с первого экрана. */
const KWORK_HEAD = '👉 Кто я: 100+ проектов на Kwork, 75 положительных отзывов из 76 - {ССЫЛКА}';

/** Пост без рекламного блока всё равно должен оставлять человеку куда пойти. */
const SOFT_BLOCK = '🔧 Контакты и примеры работ - в описании группы.';

/**
 * Реф-блоки. Ставятся только там, где тема про это по существу, и никогда вместе
 * с рекламным блоком: две ссылки в коротком тексте читаются как реклама, а не как
 * совет. Тон — «сам плачу столько-то», а не «рекомендую».
 */
const REFS = {
  visa: {
    test: /(оплат|карт|зарубежн|openai|chatgpt|подписк)/i,
    head: '💳 Чем сам плачу зарубежным сервисам - {ССЫЛКА_ВИЗА}',
    text: [
      SEP,
      '💳 Зарубежные сервисы сам оплачиваю виртуальной картой: выпуск занимает пару минут,',
      'стоит около двух тысяч разово. Вот через кого выпускаю:',
      '{ССЫЛКА_ВИЗА}',
      SEP,
    ].join('\n'),
  },
  vps: {
    test: /(сервер|хостинг|vps|развернуть|круглосуточн)/i,
    head: '🖥 На чём сам держу такие системы - {ССЫЛКА_СЕРВЕР}',
    text: [
      SEP,
      '🖥 Сервер под такие системы держу от 149 рублей в месяц за ядро и гигабайт памяти,',
      'есть площадки и в России, и за рубежом:',
      '{ССЫЛКА_СЕРВЕР}',
      SEP,
    ].join('\n'),
  },
};

/**
 * Нужен ли в этом посте рекламный блок.
 *
 * Считаем по порядковому номеру поста, а не бросаем монетку: при случайном выборе
 * блок то встаёт трижды подряд, то пропадает на десять тем, и настройка «каждый
 * третий» перестаёт что-либо значить.
 *
 * @param {number} postNumber порядковый номер поста (1, 2, 3, …)
 * @param {number} everyN 0 или 1 — блок в каждом посте
 */
export function needsAdBlock(postNumber, everyN) {
  const step = Number(everyN);
  if (!Number.isFinite(step) || step <= 1) return true;
  return postNumber % step === 0;
}

/**
 * Какая реф-ссылка уместна для этой темы. Не подходит ни одна — null, и это
 * нормальное большинство случаев.
 *
 * @param {string} subject фраза ключа и кластер одной строкой
 */
export function pickRef(subject) {
  const text = String(subject ?? '');
  for (const [name, ref] of Object.entries(REFS)) {
    if (ref.test.test(text)) return name;
  }
  return null;
}

/**
 * Блоки со ссылкой для поста.
 *
 * @param {object} options
 * @param {number} options.postNumber порядковый номер поста
 * @param {number} options.everyN настройка `ad_block_every_n`
 * @param {string} options.subject фраза ключа и кластер — по ним подбирается реф
 * @returns {{head: string, text: string, kind: 'kwork'|'visa'|'vps'|'none'}}
 */
export function buildTail({ postNumber, everyN, subject }) {
  if (needsAdBlock(postNumber, everyN)) {
    return { head: KWORK_HEAD, text: KWORK_BLOCK, kind: 'kwork' };
  }
  const ref = pickRef(subject);
  if (ref) return { head: REFS[ref].head, text: REFS[ref].text, kind: ref };
  // Вести некуда — верхнего блока нет: строка «контакты в описании группы» на первом
  // экране только занимает место, ради которого тему и открыли.
  return { head: '', text: SOFT_BLOCK, kind: 'none' };
}

/**
 * Подстановка адресов вместо плейсхолдеров.
 *
 * Вызывается дважды: до проверки длины (чтобы считать её по настоящему тексту)
 * и после сохранения поста (когда ссылка станет персональной). Незаполненный
 * плейсхолдер лучше оставить как есть, чем подставить пустоту: в панели видно,
 * что настройка не заполнена, а текст не превращается в оборванную фразу.
 */
export function renderLinks(text, links = {}) {
  let out = String(text ?? '');
  const map = {
    '{ССЫЛКА}': links.kwork,
    '{ССЫЛКА_ВИЗА}': links.visa,
    '{ССЫЛКА_СЕРВЕР}': links.vps,
  };
  for (const [placeholder, value] of Object.entries(map)) {
    if (value) out = out.replaceAll(placeholder, value);
  }
  return out;
}

/** Остались ли в тексте неподставленные плейсхолдеры. */
export function hasPlaceholders(text) {
  return /\{ССЫЛКА(_ВИЗА|_СЕРВЕР)?\}/.test(String(text ?? ''));
}
