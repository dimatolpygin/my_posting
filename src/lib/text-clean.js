/**
 * Живой человек в тексте. Проверок две, и они про разное.
 *
 * `FIRST_PERSON` — автор. Без единого «я» текст превращается в справку из
 * энциклопедии, а таких в выдаче и без нас три штуки: читателю нужен тот, кто
 * в этот вопрос упирался сам.
 *
 * `SECOND_PERSON` — читатель. Эталонный текст, на который равняемся, написан
 * во втором лице («открываете ноутбук, включаете ВПН, не грузится») и держит
 * человека этим не хуже, чем первым лицом. Поэтому порог общий: разговор
 * должен идти между двумя живыми людьми, а кто из них чаще в кадре — не важно.
 */
const FIRST_PERSON = /(^|[^а-яё])(я|мне|меня|мной|мой|моя|моё|мои|моего|моих|моим|сам|сама)([^а-яё]|$)/gi;
const SECOND_PERSON = /(^|[^а-яё])(вы|вас|вам|вами|ваш|ваша|ваше|ваши|вашего|ваших|вашем)([^а-яё]|$)/gi;

/**
 * Есть ли в тексте автор. Нужна не только проверке: редактор сокращения умеет
 * вычистить «я» вместе с водой, и вызывающий код обязан это заметить до того,
 * как обезличенный текст уйдёт на проверку и потеряет тему.
 */
export function hasAuthorVoice(text) {
  return (String(text ?? '').match(FIRST_PERSON)?.length ?? 0) > 0;
}

/** Строка подзаголовка без иконок и знаков — для сравнения со служебными названиями. */
function headingText(line) {
  return line
    .replace(/[^а-яёa-z0-9\s-]/gi, '')
    .trim()
    .toLowerCase();
}

/**
 * Проверка текста, который написала модель, — до сборки готовой темы.
 *
 * Отдельно от `validatePost` по одной причине: ссылки. В готовой теме ссылка есть
 * и обязана быть, а в тексте модели её быть не должно ни в каком виде — адрес
 * подставляет код, и выдуманный моделью адрес увёл бы человека в никуда.
 *
 * @returns {string[]} список нарушений
 */
export function validateModelText(text) {
  const problems = [];
  const value = String(text ?? '');

  // Найденный кусок называем дословно. На «в тексте есть номер телефона» модель
  // перебирает варианты вслепую и три попытки подряд возвращает тот же номер
  // (поймано на живом прогоне), а на «убери 8 900 123 45 67» убирает сразу.
  const firstMatch = (re) => value.match(re)?.[0]?.trim();

  const link = firstMatch(/(https?:\/\/\S+|www\.\S+|[a-zа-я0-9-]+\.(ru|com|net|org|io|ai)\b)/i);
  if (link) {
    // `.ai` и `.io` чаще всего оказываются не адресом, а названием сервиса из
    // прочитанной чужой статьи. Убрать его всё равно надо — чужие бренды в нашем
    // тексте не нужны, — но причину модели называем настоящую, иначе она ищет
    // ссылку там, где её нет, и возвращает тот же текст.
    const brand = /^[a-zа-я0-9-]+\.(ai|io)$/i.test(link);
    problems.push(
      brand
        ? `убери из текста «${link}»: это чужой сервис из прочитанных статей, ` +
          'называть его не нужно'
        : `убери из текста адрес «${link}»: ссылку в конец подставляет система`,
    );
  }
  const at = firstMatch(/\S*@[a-zа-я0-9_.-]+/i);
  if (at) {
    problems.push(`убери из текста «${at}»: ни почт, ни ников писать не нужно`);
  }
  const phone = firstMatch(/(\+7|\b8)[\s(-]?\d{3}[\s)-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}/);
  if (phone) {
    problems.push(`убери номер телефона «${phone}» вместе с фразой, где он стоит`);
  }
  // Адрес с номером дома. Правило есть и в промте, но модель его теряет: в живом
  // диалоге про замер окон она выдала «улица Ленина, дом 10, квартира 5». Адрес
  // выдуман, а читается как чужие персональные данные в открытом посте — и именно
  // так его прочтёт человек, который на такие вещи смотрит внимательно.
  const address = firstMatch(
    /(ул\.|улиц\w*|проспект\w*|пр-?т|переул\w*|шоссе|бульвар\w*)[^.,;\n]{2,40}[,\s]+(д\.|дом)?\s*\d+/i,
  );
  if (address) {
    problems.push(`убери адрес «${address}»: в примере диалога он выглядит как чужие данные`);
  }

  const lower = value.toLowerCase();
  const found = CLICHES.filter((cliche) => lower.includes(cliche));
  if (found.length > 0) {
    problems.push(`канцелярит и штампы: ${found.join(', ')} — переписать своими словами`);
  }

  const borrowed = BORROWED.filter((phrase) => lower.includes(phrase));
  if (borrowed.length > 0) {
    problems.push(
      `«${borrowed.join('», «')}» — это кусок примера из инструкции, показанного ` +
        'на чужой теме. Напиши начало своими словами и про свой запрос',
    );
  }

  const water = WATER.filter((phrase) => lower.includes(phrase));
  if (water.length > 0) {
    problems.push(
      `вода: «${water.join('», «')}» — из этих строк читатель ничего не узнаёт. ` +
        'Замени на то, от чего цена или срок считаются: число сценариев, число ' +
        'интеграций, есть ли внешний доступ к системе',
    );
  }

  // Автор и читатель. Пороги низкие намеренно: это пол, а не цель. Цель задаёт
  // промт, а проверка ловит только тот случай, когда текст соскользнул в справку.
  const first = value.match(FIRST_PERSON)?.length ?? 0;
  const second = value.match(SECOND_PERSON)?.length ?? 0;
  if (first === 0) {
    problems.push(
      'в тексте нет автора: ни одного «я», «мне», «у меня», «сам». Пиши как человек, ' +
        'который в этот вопрос упирался сам, а не как справочник',
    );
  }
  if (first + second < 4) {
    problems.push(
      `текст безличный: обращений к автору и читателю ${first + second}, нужно от 4. ` +
        'Говори с человеком: «вы открываете», «я пробовал», «у меня вышло»',
    );
  }

  // Подзаголовки-рубрики из промта.
  const template = value
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && line.length < 60 && !line.endsWith('.'))
    .map(headingText)
    .filter((line) => TEMPLATE_HEADINGS.includes(line));
  if (template.length > 0) {
    problems.push(
      `подзаголовки «${template.join('», «')}» — это служебные названия блоков ` +
        'из инструкции, а не заголовки для читателя. Назови каждый по смыслу ' +
        'своего абзаца',
    );
  }

  // Пункт-ярлык: «Блокировка аккаунта: использование сервисов…». Так пишет
  // конспект, а не человек, и в живых текстах системы это лезло в каждом списке.
  // Совпадает с BULLET_LABEL: то, что чистка умеет срезать, она уже срезала,
  // и сюда доходят только пункты, где ярлык нёс подлежащее и снять его нельзя.
  const label = value.match(/^\s*-\s+[А-ЯЁA-Z][^:\n]{1,45}:\s+[А-ЯЁA-Z]/m)?.[0]?.trim();
  if (label) {
    problems.push(
      `убери ярлык через двоеточие в пункте «${label.slice(0, 50)}»: ` +
        'пиши пункт обычной живой фразой',
    );
  }

  return problems;
}

/**
 * Латиница в тексте. Не нарушение, а замечание в журнал: аудитория 30+ читает
 * «Вотсап», а не латиницей, но брак поста из-за одного слова обошёлся бы дороже,
 * чем само слово. Разрешённые сокращения берём те же, что и в факт-базе.
 *
 * @returns {string[]} найденные слова латиницей
 */
export function latinWords(text, allowed = ['CRM', 'API', 'PDF', 'SMS', 'QR', 'SEO', 'IT']) {
  const ok = new Set(allowed.map((word) => word.toUpperCase()));
  const found = new Set();
  for (const match of String(text ?? '').matchAll(/[A-Za-z][A-Za-z0-9+]*/g)) {
    if (!ok.has(match[0].toUpperCase())) found.add(match[0]);
  }
  return [...found];
}
