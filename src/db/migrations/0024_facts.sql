-- Факт-база: фактура добыта один раз и дальше рекомбинируется машиной.
--
-- Кейс под каждый ключ руками не написать: при десяти темах в день это шестьсот
-- текстов в месяц. Поэтому фактура разобрана в карточки — задачи, грабли, цены,
-- возражения и цитаты отзывов, — а пост собирается из них по рецепту: ключ задаёт
-- заголовок, нишу и угол, начинка приходит из этой таблицы. Тексты расходятся
-- не стилем, а разными фактами внутри.
--
-- Источники: свои выполненные заказы, переписка с заказчиками и отзывы. Всё
-- обезличено: ни ников, ни брендов, ни адресов, ни ссылок. Проверка живёт
-- в src/lib/anonymize.js и стоит на входе в репозиторий.

CREATE TABLE IF NOT EXISTS facts (
  id           serial      PRIMARY KEY,
  kind         text        NOT NULL
                           CHECK (kind IN ('task', 'rake', 'price', 'objection', 'quote')),
  title        text        NOT NULL,
  body         text        NOT NULL,
  niche        text,
  channel      text,
  -- Кластеры ключевых запросов, где карточка уместна. Те же названия, что
  -- в keywords.cluster: по ним сборщик поста и подбирает начинку под тему.
  clusters     text[]      NOT NULL DEFAULT '{}',
  -- Счётчик и дата нужны анти-дублю: факт не чаще раза в N постов, и два поста
  -- подряд не берут одну карточку.
  used_count   integer     NOT NULL DEFAULT 0,
  last_used_at timestamptz,
  is_active    boolean     NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS facts_pick_idx ON facts (kind, used_count, last_used_at NULLS FIRST)
  WHERE is_active;
CREATE INDEX IF NOT EXISTS facts_clusters_idx ON facts USING gin (clusters);

COMMENT ON TABLE  facts IS 'Обезличенная фактура из своих заказов: начинка постов';
COMMENT ON COLUMN facts.kind IS 'task — задача клиента; rake — грабли; price — деньги; objection — возражение; quote — цитата отзыва';
COMMENT ON COLUMN facts.title IS 'Короткая метка для панели, в текст поста не идёт';
COMMENT ON COLUMN facts.body IS 'Сам факт в том виде, в каком его можно вплести в пост';
COMMENT ON COLUMN facts.niche IS 'Ниша заказчика или NULL, если факт универсальный';
COMMENT ON COLUMN facts.channel IS 'Канал общения с клиентом или NULL';

