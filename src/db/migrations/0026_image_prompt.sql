-- Этап 5: обложка под нашу тему.
--
-- Клиентский промт обложки просил «стиль ютуб обложка» — под обзоры мошеннических
-- проектов это работало: там нужен был крик. У нас в ленте собственник компании 30-50 лет,
-- и кричащая картинка с ним даёт обратный эффект — выглядит рекламой курсов, мимо которой
-- пролистывают. Плюс тема теперь приходит поисковой фразой («сколько стоит чат бот
-- для автосервиса»), а не названием проекта: если не сказать иначе, модель попробует
-- уместить в кадр всю фразу целиком мелкими буквами.
--
-- Прежняя версия остаётся в истории и откатывается из панели.
--
-- Текст продублирован в docs/prompts/image_prompt.seed.txt — оттуда его берёт сид
-- на чистой базе. Здесь он нужен потому, что сид заводит промт, только если версий
-- ещё нет: на живой базе новый текст без миграции не появится.

DO $migration$
DECLARE
  next_version integer;
BEGIN
  SELECT COALESCE(max(version), 0) + 1 INTO next_version FROM prompts WHERE key = 'image_prompt';

  UPDATE prompts SET is_active = false WHERE key = 'image_prompt' AND is_active;

  INSERT INTO prompts (key, version, body, note, is_active, created_by)
  VALUES ('image_prompt', next_version, $prompt$Нарисуй обложку к статье на тему «{{тема}}».

Где её увидят: лента Одноклассников на телефоне, картинка мелкая, пролистывают
быстро. Значит крупная надпись и один понятный предмет в кадре, без мелких деталей.

Надпись на обложке:
- по-русски, без единого слова латиницей;
- 2-4 слова, взятые из темы по смыслу, а не вся фраза целиком;
- буквы почти во всю ширину кадра, читаются при уменьшении до 160 пикселей;
- под текстом контрастная плашка или ровная заливка, чтобы он не терялся на фоне.

Кто смотрит: собственник небольшой компании, 30-50 лет, Россия. Обложка должна
выглядеть как деловая иллюстрация, а не как реклама курсов: спокойные цвета,
чистая композиция, много воздуха. Никаких кричащих стрелок, кругов, восклицательных
знаков и надписей поверх всего кадра.

Что в кадре: один предмет или сцена из темы — телефон с перепиской, стойка приёмки,
папка с бумагами, экран со списком заявок, календарь записи. Чем проще, тем лучше.

Чего в кадре быть не должно: логотипов и названий компаний, лиц крупным планом,
мелкого текста, экранов с нечитаемыми надписями, водяных знаков, коллажей
из нескольких сюжетов сразу.$prompt$,
          'этап 5: деловая обложка под поисковую фразу вместо ютуб-стиля',
          true, 'миграция 0026');

  INSERT INTO settings (key, value, title)
  VALUES ('image_prompt',
          (SELECT body FROM prompts WHERE key = 'image_prompt' AND is_active),
          'зеркало активного промта обложки')
  ON CONFLICT (key) DO UPDATE SET value = excluded.value, updated_at = now();
END
