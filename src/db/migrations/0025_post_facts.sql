-- Этап 4: сборка поста из фактов.
--
-- Меняется середина конвейера. Раньше пост писался по одному материалу: на входе
-- чужая статья, на выходе её пересказ. Теперь на входе поисковая фраза плюс набор
-- карточек из факт-базы, и текст отличается от соседних не стилем, а фактами внутри.
--
-- Что заводится здесь: связка «пост — карточки», отпечаток текста для проверки
-- схожести, настройки сборки и новый промт вместо клиентского.

-- ─────────────────────────────────────────────────────────────────────────────
-- Из каких карточек собран пост.
--
-- Нужна для трёх вещей сразу: правило «одна карточка не попадает в два поста
-- подряд» (по ней сборщик видит, что занято), счётчик использований в панели
-- и разбор постфактум — почему две темы получились похожими.
--
-- ON DELETE CASCADE с обеих сторон: связка без поста или без карточки смысла
-- не имеет, а держать висящие строки ради истории незачем — счётчик использований
-- живёт отдельной колонкой в facts и удаление поста его не откатывает. Так и надо:
-- карточка была использована, даже если пост потом снесли.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS post_facts (
  post_id    bigint      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  fact_id    integer     NOT NULL REFERENCES facts (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (post_id, fact_id)
);

CREATE INDEX IF NOT EXISTS post_facts_fact_idx ON post_facts (fact_id);

COMMENT ON TABLE post_facts IS
  'Какие карточки факт-базы ушли в какой пост. По ней работает правило «не два поста подряд».';

-- ─────────────────────────────────────────────────────────────────────────────
-- Отпечаток текста.
--
-- `shingles` — хеши цепочек по пять слов (см. src/lib/shingle.js). Хранится массивом
-- у самого поста, а не отдельной таблицей: он читается только целиком и только
-- вместе с постом, а строк было бы по три сотни на каждый текст.
--
-- `similarity` и `similar_to` — результат проверки в момент генерации: с каким постом
-- совпало сильнее всего и насколько. Хранится, чтобы в панели было видно, почему
-- тема пересобиралась, и чтобы порог можно было подбирать по фактическим числам,
-- а не на глаз.
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE posts ADD COLUMN IF NOT EXISTS shingles   text[];
ALTER TABLE posts ADD COLUMN IF NOT EXISTS similarity real;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS similar_to bigint REFERENCES posts (id) ON DELETE SET NULL;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS tail_kind  text;

COMMENT ON COLUMN posts.shingles IS
