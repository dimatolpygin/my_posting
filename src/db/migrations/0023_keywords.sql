-- Этап 2: ключевые запросы как источник тем.
--
-- Меняется вход конвейера. В клиентском проекте темы приходили из карт сайтов чужих
-- ресурсов; у нас чужих сайтов нет — на входе список поисковых фраз, под каждую пишется
-- своя тема в группе ОК. Всё, что дальше (сбор материала → генерация → обложка →
-- публикация), остаётся прежним.

-- ─────────────────────────────────────────────────────────────────────────────
-- Ключевые запросы.
--
-- `angle` — угол подачи, и он здесь не украшение. «ии агент для автомойки» и «чат бот
-- для автомойки» — разные запросы, но без разного угла по ним получится почти
-- одинаковый текст: Яндекс сочтёт темы дублями и выкинет одну из выдачи, то есть мы
-- сами себе создадим конкурента. Угол уходит в промт параметром и разводит тексты
-- по существу, а не по стилю.
--
-- `serp_weakness` — сколько UGC-страниц (форумы, соцсети, дзен, отзовики) в топ-10.
-- Отбор идёт по нему, а не по частотности: ключ с частотой 30 и пустым топом даёт
-- больше, чем ключ с частотой 500 и забитым. Пока не заполняется — снятие выдачи
-- это отдельная задача, колонка заведена под неё заранее.
--
-- `phrase` уникальна: она же становится заголовком темы, а значит `<title>` страницы.
-- Две темы с одинаковым заголовком конкурировали бы друг с другом в выдаче.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS keywords (
  id            serial      PRIMARY KEY,
  phrase        text        NOT NULL UNIQUE,
  cluster       text,
  angle         text,
  frequency     integer,
  serp_weakness integer,
  priority      integer     NOT NULL DEFAULT 0,
  -- new — ждёт очереди; queued — зарезервирован прогоном; used — стал материалом;
  -- skipped — снят с очереди человеком или отклонён дедупом
  status        text        NOT NULL DEFAULT 'new'
                            CHECK (status IN ('new', 'queued', 'used', 'skipped')),
  skip_reason   text,
  article_id    bigint      REFERENCES articles (id) ON DELETE SET NULL,
  -- Когда ключ зарезервирован прогоном. По нему снимаются зависшие резервы:
  -- прогон, упавший вместе с процессом, вернуть фразу в очередь уже не успеет.
  queued_at     timestamptz,
  used_at       timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Очередь: сначала приоритетные, внутри приоритета — по порядку заведения.
CREATE INDEX IF NOT EXISTS keywords_queue_idx ON keywords (status, priority DESC, id);

COMMENT ON TABLE keywords IS
  'Поисковые фразы — вход конвейера. Одна фраза = одна тема в группе ОК.';
COMMENT ON COLUMN keywords.angle IS
  'Угол подачи. Уходит в промт параметром и не даёт похожим фразам превратиться '
  'в одинаковый текст, который Яндекс склеит как дубль.';
COMMENT ON COLUMN keywords.serp_weakness IS
  'Сколько UGC-страниц в топ-10. Главный критерий отбора: слабая выдача важнее частотности.';

-- Связь материала с ключом. Нужна дважды: планировщик по ней разносит кластеры,
-- а учёт переходов (этап 6) свяжет клик с породившей его фразой.
ALTER TABLE articles ADD COLUMN IF NOT EXISTS keyword_id integer REFERENCES keywords (id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS articles_keyword_idx ON articles (keyword_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- Новый режим обнаружения. `sitemap` читает карту сайта, `custom` — свой адаптер
-- под чужую структуру, `keywords` берёт очередную фразу из таблицы выше.
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE sources DROP CONSTRAINT IF EXISTS sources_discovery_check;
ALTER TABLE sources ADD CONSTRAINT sources_discovery_check
  CHECK (discovery IN ('sitemap', 'custom', 'keywords'));

